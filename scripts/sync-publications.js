import { writeFile } from 'node:fs/promises'

import { parseWorks } from '../src/lib/orcid.js'

const orcid = '0009-0006-3587-3380'
const source = `https://pub.orcid.org/v3.0/${orcid}/works`
const target = new URL('../src/content/publications.generated.json', import.meta.url)

const response = await fetch(source, {
  headers: { Accept: 'application/json' },
  signal: AbortSignal.timeout(30_000),
})
if (!response.ok) {
  throw new Error(`ORCID answered ${response.status} ${response.statusText}`)
}

const works = parseWorks(await response.json())
// An empty answer is far likelier an ORCID fault than a real record, so keep the snapshot.
if (works.length === 0) throw new Error('ORCID returned no works')

const data = {
  '//': 'Generated by `npm run sync:publications` from ORCID. Do not edit by hand.',
  source,
  works,
}
await writeFile(target, `${JSON.stringify(data, null, 2)}\n`)
console.log(`Wrote ${works.length} works to ${target.pathname}`)
